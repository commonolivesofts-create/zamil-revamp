-- HRMS-ID-UK-001: READ-ONLY pre-check for the unique constraints in 01-migration.sql.
-- Run as a user that can SELECT from the XXZP tables (TEST first). Every query must return 0 in
-- DUPLICATE_IDS and NULL_IDS before 01-migration.sql may run. No query changes data.
-- See docs/testing/hrms-recruitment-audit.md §8.5 and the README in this folder.

SELECT 'XXZPI_PER_REQUISITIONS_ALL.REQUISITION_ID' AS ID_COLUMN,
       (SELECT COUNT(*) FROM (SELECT REQUISITION_ID FROM XXZP.XXZPI_PER_REQUISITIONS_ALL
                               WHERE REQUISITION_ID IS NOT NULL
                               GROUP BY REQUISITION_ID HAVING COUNT(*) > 1)) AS DUPLICATE_IDS,
       (SELECT COUNT(*) FROM XXZP.XXZPI_PER_REQUISITIONS_ALL WHERE REQUISITION_ID IS NULL) AS NULL_IDS
  FROM DUAL;

