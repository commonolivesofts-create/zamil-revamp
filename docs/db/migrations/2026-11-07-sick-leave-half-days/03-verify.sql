-- SICK-LEAVE-HALF-DAYS-001: read-only verification after 01-migration.sql.

SELECT COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, CHAR_LENGTH,
       NULLABLE, DATA_DEFAULT
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND COLUMN_NAME IN ('LEAVE_DAYS', 'FROM_DAY_TYPE', 'TO_DAY_TYPE')
ORDER BY COLUMN_NAME;

SELECT COUNT(*) AS FRACTIONAL_LEAVE_ROWS
FROM XXZP.XXZP_SICK_LEAVE
WHERE LEAVE_DAYS <> TRUNC(LEAVE_DAYS);

SELECT CONSTRAINT_NAME, STATUS, VALIDATED
FROM ALL_CONSTRAINTS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND CONSTRAINT_NAME IN ('XXZP_SL_FROM_DAY_TYPE_CK', 'XXZP_SL_TO_DAY_TYPE_CK')
ORDER BY CONSTRAINT_NAME;

SELECT COUNT(*) AS INVALID_DAY_TYPE_ROWS
FROM XXZP.XXZP_SICK_LEAVE
WHERE FROM_DAY_TYPE NOT IN ('FULL', 'HALF')
   OR TO_DAY_TYPE NOT IN ('FULL', 'HALF');

SELECT COLUMN_NAME AS LEFTOVER_STAGING_COLUMN
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND COLUMN_NAME IN ('LEAVE_DAYS_NUM_TMP', 'LEAVE_DAYS_VC_OLD');
