  ATTRIBUTE11, ATTRIBUTE12, ATTRIBUTE13, ATTRIBUTE14, ATTRIBUTE15, CREATION_DATE, CREATED_BY,
  LAST_UPDATE_DATE, LAST_UPDATED_BY, OBJECT_VERSION_NUMBER, LAST_UPDATE_LOGIN, REMARK, TOTAL_PACKAGE)
