/** "VARCHAR2(30 CHAR)", "NUMBER(15,0)", "DATE" … for display only. */
export function typeLabel(column) {
  const { oracleType, charLength, dataLength, precision, scale } = column
  if (/CHAR/.test(oracleType) && charLength) return `${oracleType}(${charLength})`
  if (oracleType === 'NUMBER' && precision !== null && precision !== undefined) {
    return scale ? `NUMBER(${precision},${scale})` : `NUMBER(${precision})`
  }
  if (oracleType === 'RAW' && dataLength) return `RAW(${dataLength})`
  return oracleType
}

let uid = 0
const nextUid = () => `key-${(uid += 1)}`

export function emptyKey() {
  return { uid: nextUid(), code: '', columns: [], basis: '', evidenceRef: '', rationale: '' }
}

/**
 * Editor state: one row per live column (plus stored columns the source no longer has, flagged
 * `missing`) and the key candidates. `included` puts the column into the mapping's allowlist;
 * `exposed` makes it available to forms; `dataClass` is required for every included column.
 */
export function editorState({ liveColumns = [], config = null }) {
  const stored = new Map((config?.columns ?? []).map((column) => [column.name, column]))
  const rows = liveColumns.map((column) => {
    const saved = stored.get(column.name)
    return {
      ...column,
      missing: false,
      included: Boolean(saved),
      exposed: saved ? saved.exposed : false,
      dataClass: saved ? saved.dataClass : 'INTERNAL',
    }
  })
  const live = new Set(liveColumns.map((column) => column.name))
  for (const saved of config?.columns ?? []) {
    if (!live.has(saved.name)) {
      rows.push({ ...saved, supported: false, keyEligible: false, missing: true, included: true })
    }
  }
  const keys = (config?.keyCandidates ?? []).map((key) => ({
    uid: nextUid(),
    code: key.code,
    columns: [...key.columns],
    basis: key.assurance?.basis ?? '',
    evidenceRef: key.assurance?.evidenceRef ?? '',
    rationale: key.assurance?.rationale ?? '',
    saved: key,
  }))
  return { columns: rows, keys }
}

/**
 * Preview of how the database treats a key (mirrors keyAssurance.assessKeyCandidate): an
 * ENABLED + VALIDATED primary key, or an enabled/validated unique constraint or VALID
 * non-function-based unique index whose columns are all NOT NULL, covering the key columns or a
 * subset of them, makes it DATABASE_ENFORCED; anything else is DECLARED (provisional).
 */
export function previewEnforcement(columns, snapshot) {
  if (!columns.length || !snapshot) return { enforcement: 'DECLARED', enforcedBy: null }
  const byName = new Map(snapshot.columns.map((column) => [column.name, column]))
  const allNotNull = columns.every((name) => byName.get(name)?.nullable === false)
  const covers = (enforced) => enforced.length > 0 && enforced.every((name) => columns.includes(name))
  const candidates = [
    ...snapshot.constraints
      .filter((c) => c.status === 'ENABLED' && c.validated === 'VALIDATED' && (c.type === 'P' || allNotNull))
      .map((c) => ({ name: c.name, columns: c.columns })),
    ...snapshot.uniqueIndexes
      .filter((i) => i.status === 'VALID' && !i.functionBased && allNotNull)
      .map((i) => ({ name: i.name, columns: i.columns })),
  ].filter((item) => covers(item.columns))
  if (!candidates.length) return { enforcement: 'DECLARED', enforcedBy: null }
  const best = candidates.find((item) => item.columns.length === columns.length) ?? candidates[0]
  return { enforcement: 'DATABASE_ENFORCED', enforcedBy: best.name }
}

const textError = (value, max, label) => {
  const text = String(value ?? '').trim()
  if (!text) return `${label} is required.`
  if (text.length > max) return `${label} must be at most ${max} characters.`
  if (CONTROL_CHARACTERS.test(text)) return `${label} contains characters that are not allowed.`
  return null
}

/**
 * Client-side checks → { valid, errors: { columns, keys: { [uid]: { code, columns, basis,
 * evidenceRef, rationale } } }, payload }. The payload holds only author choices.
 */
export function validateEditor(state, snapshot) {
  const errors = { columns: null, keys: {} }
  const included = state.columns.filter((column) => column.included)
  if (!included.length) errors.columns = 'Include at least one column in the mapping.'
  else if (included.some((column) => column.missing)) {
    errors.columns = 'Some saved columns no longer exist in the source. Remove them from the mapping.'
  } else if (included.some((column) => column.exposed && !column.supported)) {
    errors.columns = 'A column of an unsupported type (for example BLOB) cannot be exposed.'
  }
  const exposed = new Set(included.filter((column) => column.exposed).map((column) => column.name))
  if (state.keys.length > MAX_KEYS) errors.columns = errors.columns || `At most ${MAX_KEYS} key candidates are allowed.`

  const codes = state.keys.map((key) => key.code.trim())
  const payloadKeys = state.keys.map((key, index) => {
    const keyErrors = {}
    const code = codes[index]
    if (!code) keyErrors.code = 'Key code is required.'
    else if (!CODE.test(code)) keyErrors.code = 'Use upper-case letters, digits and underscores, starting with a letter (at most 80).'
    else if (codes.indexOf(code) !== index) keyErrors.code = 'Each key code must be unique.'
    if (!key.columns.length) keyErrors.columns = 'Choose at least one column.'
    else if (key.columns.length > MAX_KEY_COLUMNS) keyErrors.columns = `At most ${MAX_KEY_COLUMNS} columns.`
    else if (key.columns.some((name) => !exposed.has(name))) keyErrors.columns = 'Every key column must be included and exposed.'
    const { enforcement } = previewEnforcement(key.columns, snapshot)
    const declared = enforcement === 'DECLARED'
    if (declared) {
      if (!ASSURANCE_BASES.includes(key.basis)) keyErrors.basis = 'Choose how uniqueness is assured.'
      const evidence = textError(key.evidenceRef, 500, 'Evidence reference')
      if (evidence) keyErrors.evidenceRef = evidence
      const rationale = textError(key.rationale, 1000, 'Rationale')
      if (rationale) keyErrors.rationale = rationale
    }
    if (Object.keys(keyErrors).length) errors.keys[key.uid] = keyErrors
    return {
      code,
      columns: [...key.columns],
      assurance: declared && key.basis
        ? { basis: key.basis, evidenceRef: String(key.evidenceRef).trim(), rationale: String(key.rationale).trim() }
        : null,
    }
  })

  const payload = {
    columns: included.map((column) => ({ name: column.name, exposed: Boolean(column.exposed), dataClass: column.dataClass })),
    keyCandidates: payloadKeys,
  }
  const valid = !errors.columns && Object.keys(errors.keys).length === 0
  return { valid, errors, payload }
}

/** Canonical comparison of two payloads (unsaved-changes indicator). */
export function samePayload(a, b) {
  const norm = (p) => JSON.stringify({
    columns: [...p.columns].sort((x, y) => (x.name < y.name ? -1 : 1)),
    keyCandidates: [...p.keyCandidates].sort((x, y) => (x.code < y.code ? -1 : 1)),
  })
  return norm(a) === norm(b)
}

/** Findings from a refused write (400 SOURCE_MAPPING_INVALID / 409 revalidation, …). */
export function findingsFromError(error) {
  if (!Array.isArray(error?.details)) return []
  return error.details
    .filter((item) => item && typeof item.code === 'string')
    .map((item) => ({
      severity: item.severity === 'WARNING' ? 'WARNING' : 'ERROR',
      code: item.code,
      path: typeof item.field === 'string' ? item.field : '$',
      message: typeof item.message === 'string' ? item.message : item.code,
    }))
}

export function groupFindings(findings = []) {
  return {
    errors: findings.filter((finding) => finding.severity === 'ERROR'),
    warnings: findings.filter((finding) => finding.severity === 'WARNING'),
  }
}

