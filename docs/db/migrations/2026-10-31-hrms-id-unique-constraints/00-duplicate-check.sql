-- The flag registry maps an orientation header to its table pair. Both header tables have their
-- own identity, so the same FORM_HEADER_ID can exist in both; this counts ambiguous mappings.
SELECT 'XXZP_NHT_MASTER_FLAG.FORM_HEADER_ID' AS ID_COLUMN,
       (SELECT COUNT(*) FROM (SELECT FORM_HEADER_ID FROM XXZP.XXZP_NHT_MASTER_FLAG
                               WHERE FORM_HEADER_ID IS NOT NULL
                               GROUP BY FORM_HEADER_ID HAVING COUNT(*) > 1)) AS DUPLICATE_IDS,
       (SELECT COUNT(*) FROM XXZP.XXZP_NHT_MASTER_FLAG WHERE FORM_HEADER_ID IS NULL) AS NULL_IDS
  FROM DUAL;

-- Header IDs present in BOTH orientation header tables (would make the flag registry ambiguous).
SELECT 'ORIENTATION HEADER_ID IN BOTH TABLES' AS ID_COLUMN,
       (SELECT COUNT(*) FROM XXZP.XXZP_NEW_HIRETRAINING_SS_HDR_T s
         WHERE EXISTS (SELECT 1 FROM XXZP.XXZP_NEW_HIRETRAIN_PROD_HDR_T p
                        WHERE p.HEADER_ID = s.HEADER_ID)) AS DUPLICATE_IDS,
       0 AS NULL_IDS
  FROM DUAL;

-- Existing unique indexes (a unique index without a constraint also enforces uniqueness).
SELECT i.TABLE_NAME, i.INDEX_NAME, c.COLUMN_NAME
  FROM ALL_INDEXES i
  JOIN ALL_IND_COLUMNS c ON c.INDEX_OWNER = i.OWNER AND c.INDEX_NAME = i.INDEX_NAME
 WHERE i.OWNER = 'XXZP' AND i.UNIQUENESS = 'UNIQUE'
   AND i.TABLE_NAME IN ('XXZPI_PER_REQUISITIONS_ALL', 'XXZP_ALL_ATTACHMENTS',
                        'XXZP_INTERVW_ASSESMNT_HEADER_T', 'XXZP_PAF_PROBATION_HEADER',
                        'XXZP_PAF_PROBATION_LINES', 'XXZP_NEW_HIRETRAINING_SS_HDR_T',
                        'XXZP_NEW_HIRETRAIN_SS_LINE_T', 'XXZP_EMPLOYMENT_OFFER_HEADER_T',
                        'XXZP_NHT_MASTER_FLAG')
 ORDER BY i.TABLE_NAME, i.INDEX_NAME;
