// Oracle DDL generated from the table definitions. Only CREATE / ALTER ... ADD — never DROP.
import { ALL_TABLES, toSnake, type Col, type TableDef } from './tables';

export function colType(spec: Col): string {
  switch (spec.t) {
    case 'int':
      return 'NUMBER(19)';
    case 'num':
      return 'NUMBER';
    case 'text':
      return `VARCHAR2(${spec.len ?? 200} CHAR)`;
    case 'date':
      return 'DATE';
    case 'ts':
      return 'TIMESTAMP(3)';
    case 'flag':
      return 'CHAR(1)';
  }
}

export function columnSql(def: TableDef, col: string, spec: Col): string {
  const c = toSnake(col);
  let s = `${c} ${colType(spec)}`;
  if (def.identity && col === def.pk) return `${s} GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL`;
  if (spec.def) s += ` DEFAULT ${spec.def}`;
  if (spec.req) s += ' NOT NULL';
  if (spec.t === 'flag') s += ` CHECK (${c} IN ('Y','N'))`;
  return s;
}

export function createTableSql(def: TableDef, prefix: string): string[] {
  const t = prefix + def.name;
  const lines = Object.entries(def.cols).map(([c, s]) => '  ' + columnSql(def, c, s));
  lines.push(`  CONSTRAINT ${t}_PK PRIMARY KEY (${toSnake(def.pk)})`);
  (def.unique ?? []).forEach((u, i) => lines.push(`  CONSTRAINT ${t}_UK${i + 1} UNIQUE (${u.map(toSnake).join(', ')})`));
  return [`CREATE TABLE ${t} (\n${lines.join(',\n')}\n)`, ...indexSql(def, prefix)];
}

export function indexSql(def: TableDef, prefix: string): string[] {
  const t = prefix + def.name;
  return (def.indexes ?? []).map((ix, i) => `CREATE INDEX ${t}_IX${i + 1} ON ${t} (${ix.map(toSnake).join(', ')})`);
}

export function fullSchemaSql(prefix: string): string {
  const out = [
    `-- TrainingHub schema (generated from apps/api/src/db/tables.ts — do not edit by hand).`,
    `-- Every object starts with ${prefix}. Run "npm run db:migrate" instead of this file.`,
    '',
  ];
  for (const def of ALL_TABLES) for (const s of createTableSql(def, prefix)) out.push(s + ';', '');
  out.push(
    `CREATE TABLE ${prefix}SCHEMA_MIGRATIONS (\n  VERSION_NO NUMBER(10) NOT NULL,\n  DESCRIPTION VARCHAR2(400 CHAR),\n  APPLIED_AT TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,\n  CONSTRAINT ${prefix}SCHEMA_MIGRATIONS_PK PRIMARY KEY (VERSION_NO)\n);`,
  );
  return out.join('\n');
}
