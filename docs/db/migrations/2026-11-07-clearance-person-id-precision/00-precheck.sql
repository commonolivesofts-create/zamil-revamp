-- EMPLOYEE-CLEARANCE-PERSON-ID-001: read-only precheck. No data or schema changes.

SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE (OWNER = 'XXZP' AND TABLE_NAME = 'XX_DIGI_EMP_MASTER' AND COLUMN_NAME = 'PERSON_ID')
   OR (OWNER = 'XXZP'
       AND TABLE_NAME IN (
         'XX_CLEARANCE_HEADER', 'XX_CLEARANCE_IT', 'XX_CLEARANCE_EMPLOYEES',
         'XX_CLEARANCE_QUALITY', 'XX_CLEARANCE_WH', 'XX_CLEARANCE_ACCOUNTS',
         'XX_CLEARANCE_ADMIN'
       )
       AND COLUMN_NAME = 'PERSON_ID')
ORDER BY OWNER, TABLE_NAME;

SELECT COUNT(*) AS SOURCE_IDS_OVER_TEN_DIGITS
FROM XXZP.XX_DIGI_EMP_MASTER
WHERE ABS(PERSON_ID) >= 10000000000;

SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE, CC.COLUMN_NAME
FROM ALL_CONSTRAINTS C
JOIN ALL_CONS_COLUMNS CC
  ON CC.OWNER = C.OWNER
 AND CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
WHERE C.OWNER = 'XXZP'
  AND C.TABLE_NAME IN (
    'XX_CLEARANCE_HEADER', 'XX_CLEARANCE_IT', 'XX_CLEARANCE_EMPLOYEES',
    'XX_CLEARANCE_QUALITY', 'XX_CLEARANCE_WH', 'XX_CLEARANCE_ACCOUNTS',
    'XX_CLEARANCE_ADMIN'
  )
  AND CC.COLUMN_NAME = 'PERSON_ID'
ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME;
