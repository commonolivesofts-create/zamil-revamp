/** Column names and key codes in the order of the draft that was submitted. */
export const draftOrder = (draft) => ({
  columns: (draft?.columns ?? []).map((column) => column.name),
  keys: (draft?.keyCandidates ?? []).map((key) => key.code),
})

/**
 * "keyCandidates[1].columns[0]" → "Key candidate ORG_LINE" (a readable location). Paths index
 * into the submitted draft, so `order` is that draft's order (see draftOrder).
 */
export function describePath(path, order) {
  if (!path || path === '$') return 'Whole mapping'
  const key = /^keyCandidates\[(\d+)\]/.exec(path)
  if (key) return `Key candidate ${order?.keys?.[Number(key[1])] || Number(key[1]) + 1}`
  const column = /^columns\[(\d+)\]/.exec(path)
  if (column) return `Column ${order?.columns?.[Number(column[1])] ?? Number(column[1]) + 1}`
  if (path === 'source' || path === 'dictionary' || path === 'handler') return 'Source object'
  return path
}

/** Author draft of a stored configuration, in its stored order (what revalidation submits). */
export const storedDraft = (config) => ({
  columns: (config?.columns ?? []).map(({ name, exposed, dataClass }) => ({ name, exposed, dataClass })),
  keyCandidates: (config?.keyCandidates ?? []).map(({ code, columns, assurance }) => ({
    code,
    columns: [...columns],
    assurance: assurance ? { basis: assurance.basis, evidenceRef: assurance.evidenceRef, rationale: assurance.rationale } : null,
  })),
})

