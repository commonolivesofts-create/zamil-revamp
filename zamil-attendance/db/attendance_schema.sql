-- =============================================================================
-- Zamil Attendance System: ADW tables (schema XXZP)
-- =============================================================================
-- Created for the Zamil Revamp TEST ADW, where these tables did not exist.
-- No original DDL was available, so the definitions are REVERSE-ENGINEERED from
-- the application code (column lists, bind formats, form validation lengths).
-- Replace them with the production DDL (DBMS_METADATA.GET_DDL) when available.
--
-- Additive only: CREATE statements, never DROP/ALTER of existing objects.
-- Run as XXZP with the tables owned by XXZP (Timetable_model::has_column reads
-- ALL_TAB_COLUMNS for the connection user). Re-running is safe: an existing
-- table raises ORA-00955 and is skipped by the runner.
--
-- Format conventions the code relies on:
--   * Time-of-day columns are 'HH24:MI' strings (VARCHAR2), not DATE.
--   * ATT_SHEET minutes/hours (TOTAL_MINUTES, EARLY, LATE, OVERTIME) are
--     numeric strings ('.' decimal); the code TO_NUMBERs them after REGEXP_LIKE.
--   * XX_DIGI_EMP_ABSENCE_TYPE.LEAVE_*_DATE are 'DD-MM-YY' strings
--     (read with TO_DATE(x,'DD-MM-RR')).
--   * ATT_SHEET / ATT_CARD HEADER_ID and PUNCH_* share types (UNION ALL).
-- =============================================================================

-- Raw punches uploaded from the attendance devices/file (MERGE on EMP_NO+day).
CREATE TABLE XX_DIGI_ATT_ATT_CARD (
    HEADER_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EMP_NO      VARCHAR2(30)  NOT NULL,
    EMP_NAME    VARCHAR2(240),
    ATT_DATE    DATE          NOT NULL,
    PUNCH_IN    VARCHAR2(20),
    PUNCH_OUT   VARCHAR2(20),
    CONSTRAINT XX_DIGI_ATT_ATT_CARD_PK PRIMARY KEY (HEADER_ID),
    CONSTRAINT XX_DIGI_ATT_ATT_CARD_U1 UNIQUE (EMP_NO, ATT_DATE)
);

-- Calculated daily timesheet (one row per employee per day).
CREATE TABLE XX_DIGI_ATT_ATT_SHEET (
    HEADER_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EMP_NO         VARCHAR2(30)  NOT NULL,
    EMP_NAME       VARCHAR2(240),
    SHIFT          VARCHAR2(240),
    ATT_DATE       DATE          NOT NULL,
    CHECK_IN       VARCHAR2(20),
    PUNCH_IN       VARCHAR2(20),
    CHECK_OUT      VARCHAR2(20),
    PUNCH_OUT      VARCHAR2(20),
    TOTAL_MINUTES  VARCHAR2(20),
    EARLY          VARCHAR2(20),
    LATE           VARCHAR2(20),
    OVERTIME       VARCHAR2(20),
    ABSENCE        VARCHAR2(240),
    CONSTRAINT XX_DIGI_ATT_ATT_SHEET_PK PRIMARY KEY (HEADER_ID),
    CONSTRAINT XX_DIGI_ATT_ATT_SHEET_U1 UNIQUE (EMP_NO, ATT_DATE)
);

-- Manual payroll-file overrides per employee and payroll period.
CREATE TABLE XX_DIGI_ATT_PYRL_FILE_ADJ (
    ADJ_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EMP_NO        VARCHAR2(30)  NOT NULL,
    EMP_NAME      VARCHAR2(240),
    FROM_DATE     DATE          NOT NULL,
    TO_DATE       DATE          NOT NULL,
    LATE          VARCHAR2(30),
    EARLY         VARCHAR2(30),
    TOT_DELAY     VARCHAR2(30),
    OVERTIME_HRS  VARCHAR2(30),
    ABSENCE_WO    VARCHAR2(30),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT XX_DIGI_ATT_PYRL_FILE_ADJ_PK PRIMARY KEY (ADJ_ID),
    CONSTRAINT XX_DIGI_ATT_PYRL_FILE_ADJ_U1 UNIQUE (EMP_NO, FROM_DATE, TO_DATE)
);

-- Leave / absence records (fed externally; the app only reads and updates
-- APPROVAL_STATUS). No surrogate key in the original design.
CREATE TABLE XX_DIGI_EMP_ABSENCE_TYPE (
    EMP_NO            VARCHAR2(30)  NOT NULL,
    EMP_NAME          VARCHAR2(240),
    DEPARTMENT_NAME   VARCHAR2(240),
    POSITION          VARCHAR2(240),
    LEAVE_TYPE        VARCHAR2(240),
    LEAVE_START_DATE  VARCHAR2(20),
    LEAVE_END_DATE    VARCHAR2(20),
    TOTAL_DAYS        NUMBER,
    APPROVAL_STATUS   VARCHAR2(30)
);

CREATE INDEX XX_DIGI_EMP_ABSENCE_TYPE_N1 ON XX_DIGI_EMP_ABSENCE_TYPE (EMP_NO);

-- Shift header.
CREATE TABLE XX_DIGI_SHIFT_PR (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    UUID               VARCHAR2(36)  NOT NULL,
    SHIFT_NAME         VARCHAR2(100),
    START_DATE         DATE,
    END_DATE           DATE,
    STATUS             VARCHAR2(50)  DEFAULT 'ACTIVE',
    CHECK_IN           VARCHAR2(10),
    CHECK_OUT          VARCHAR2(10),
    WEEKDAY_OVRTM_CAP  VARCHAR2(20),
    WEEKEND_OVRTM_CAP  VARCHAR2(20),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT XX_DIGI_SHIFT_PR_PK PRIMARY KEY (ID),
    CONSTRAINT XX_DIGI_SHIFT_PR_U1 UNIQUE (UUID)
);

-- Shift weekday detail (1 = Sunday ... 7 = Saturday). No FK: deleting a shift
-- header does not delete its detail rows in the application.
CREATE TABLE XX_DIGI_SHIFT_PR_DTL (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SHIFT_PR_ID   NUMBER        NOT NULL,
    UUID          VARCHAR2(36),
    DAY_NO        NUMBER(1)     NOT NULL,
    WEEKDAY_NAME  VARCHAR2(20),
    PUNCH_IN      VARCHAR2(10),
    PUNCH_OUT     VARCHAR2(10),
    GROSS_TIME    VARCHAR2(10),
    STATUS        VARCHAR2(50)  DEFAULT 'ACTIVE',
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT XX_DIGI_SHIFT_PR_DTL_PK PRIMARY KEY (ID),
    CONSTRAINT XX_DIGI_SHIFT_PR_DTL_U1 UNIQUE (SHIFT_PR_ID, DAY_NO)
);

-- Employee shift assignments (versioned: edits inactivate the old row).
CREATE TABLE XX_DIGI_TIMETABLE_PR (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    UUID               VARCHAR2(36)  NOT NULL,
    EMP_NO             NUMBER        NOT NULL,
    EMP_NAME           VARCHAR2(240),
    SHIFT_ID           NUMBER,
    START_DATE         DATE,
    END_DATE           DATE,
    STATUS             VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    OVERTIME_ALLOWED   VARCHAR2(1)   DEFAULT 'N',
    EXCLUDE_TIMESHEET  VARCHAR2(1)   DEFAULT 'N',
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT XX_DIGI_TIMETABLE_PR_PK PRIMARY KEY (ID),
    CONSTRAINT XX_DIGI_TIMETABLE_PR_U1 UNIQUE (UUID)
);

CREATE INDEX XX_DIGI_TIMETABLE_PR_N1 ON XX_DIGI_TIMETABLE_PR (EMP_NO, STATUS);

-- Public holidays / occasions. SHIFT_ID is a comma-separated list of shift IDs.
CREATE TABLE XX_DIGI_ATT_OCCASIONS (
    OCCASION_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    OCCASION_NAME     VARCHAR2(255),
    FROM_DATE         DATE,
    TO_DATE           DATE,
    OCCASION_TYPE     VARCHAR2(100),
    SHIFT_ID          VARCHAR2(1000),
    COUNT_AS_PRESENT  VARCHAR2(1)   DEFAULT 'Y',
    PAID_HOLIDAY      VARCHAR2(1)   DEFAULT 'Y',
    IS_ACTIVE         VARCHAR2(1)   DEFAULT 'Y',
    REMARKS           VARCHAR2(500),
    CREATED_BY        VARCHAR2(100),
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_BY        VARCHAR2(100),
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT XX_DIGI_ATT_OCCASIONS_PK PRIMARY KEY (OCCASION_ID)
);
