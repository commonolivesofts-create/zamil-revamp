-- Profile images are separated from the locked authentication table.
-- Confirm the deployed dictionary and target grants before applying.
CREATE TABLE XX_ZRV_USER_PROFILE_IMAGES (
  USER_ID NUMBER(19,0) NOT NULL,
  IMAGE_BLOB BLOB NOT NULL,
  MIME_TYPE VARCHAR2(32 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT (SYSTIMESTAMP AT TIME ZONE 'UTC') NOT NULL,
  UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT (SYSTIMESTAMP AT TIME ZONE 'UTC') NOT NULL,
  CONSTRAINT PK_ZRV_USER_PROFILE_IMAGES PRIMARY KEY (USER_ID),
  CONSTRAINT FK_ZRV_UPI_USER FOREIGN KEY (USER_ID) REFERENCES XX_ZRV_USERS (USER_ID),
  CONSTRAINT CK_ZRV_UPI_MIME CHECK (MIME_TYPE IN ('image/png', 'image/jpeg', 'image/webp'))
);
