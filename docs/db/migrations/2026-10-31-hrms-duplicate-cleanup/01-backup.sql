-- HRMS-DUP-CLEAN-001 backup. NOT APPLIED. Creates backup tables holding every row the cleanup
-- touches (CTAS commits implicitly). Run after 00-precheck.sql matched, as the XXZP owner.
-- Keep these tables until the owner signs off; 04-rollback.sql restores from them.

CREATE TABLE XXZP.XXZP_DUPFIX_REQ_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZPI_PER_REQUISITIONS_ALL t
   WHERE t.REQUISITION_ID = 100800;

CREATE TABLE XXZP.XXZP_DUPFIX_INT_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZP_INTERVW_ASSESMNT_HEADER_T t
   WHERE t.HEADER_ID = 677;

CREATE TABLE XXZP.XXZP_DUPFIX_INT_EVAL_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZP_INTERVIEW_EVAL_T t
   WHERE t.HEADER_ID = 677;

CREATE TABLE XXZP.XXZP_DUPFIX_INT_PSPEC_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZP_PERSONAL_SPEC_T t
   WHERE t.HEADER_ID = 677;

CREATE TABLE XXZP.XXZP_DUPFIX_INT_JCOMP_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZP_JOB_COMPETENCY_T t
   WHERE t.HEADER_ID = 677;

CREATE TABLE XXZP.XXZP_DUPFIX_ATT_BAK AS
  SELECT ROWIDTOCHAR(t.ROWID) AS ORIG_ROWID, SYSDATE AS BACKED_UP_ON, t.*
    FROM XXZP.XXZP_ALL_ATTACHMENTS t
   WHERE t.HEADER_ID IN (SELECT HEADER_ID FROM XXZP.XXZP_ALL_ATTACHMENTS
                          GROUP BY HEADER_ID HAVING COUNT(*) > 1);

-- Renumbering map for interview 677 (filled by 02-cleanup.sql).
CREATE TABLE XXZP.XXZP_DUPFIX_INT_MAP (
  OLD_HEADER_ID NUMBER NOT NULL,
  NEW_HEADER_ID NUMBER NOT NULL,
  CREATED_BY    NUMBER NOT NULL,
  MAPPED_ON     DATE   DEFAULT SYSDATE NOT NULL
);

-- Verification: expect REQ 2, INT 2, EVAL 3, PSPEC 3, JCOMP 3, ATT 7128 (TEST figures).
SELECT 'REQ' T, COUNT(*) FROM XXZP.XXZP_DUPFIX_REQ_BAK UNION ALL
SELECT 'INT', COUNT(*) FROM XXZP.XXZP_DUPFIX_INT_BAK UNION ALL
SELECT 'EVAL', COUNT(*) FROM XXZP.XXZP_DUPFIX_INT_EVAL_BAK UNION ALL
SELECT 'PSPEC', COUNT(*) FROM XXZP.XXZP_DUPFIX_INT_PSPEC_BAK UNION ALL
SELECT 'JCOMP', COUNT(*) FROM XXZP.XXZP_DUPFIX_INT_JCOMP_BAK UNION ALL
SELECT 'ATT', COUNT(*) FROM XXZP.XXZP_DUPFIX_ATT_BAK;
