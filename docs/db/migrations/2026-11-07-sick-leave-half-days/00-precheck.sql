-- SICK-LEAVE-HALF-DAYS-001: read-only precheck. No data or schema changes.
-- Run before 01-migration.sql. Do not proceed if the existing schema differs from the README.

SELECT COUNT(*) AS SICK_LEAVE_TABLES
FROM ALL_TABLES
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE';

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE,
       NULLABLE, DATA_DEFAULT, IDENTITY_COLUMN
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME IN ('XXZP_SICK_LEAVE', 'XXZP_ALL_ATTACHMENTS')
  AND COLUMN_NAME IN ('HEADER_ID', 'LEAVE_DAYS', 'FROM_DAY_TYPE', 'TO_DAY_TYPE')
ORDER BY TABLE_NAME, COLUMN_NAME;

SELECT COLUMN_NAME
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND COLUMN_NAME IN ('LEAVE_DAYS_NUM_TMP', 'LEAVE_DAYS_VC_OLD');

-- LEAVE_DAYS is VARCHAR2 in the current test schema. Confirm every populated value
-- can be converted before ALTER TABLE changes it to NUMBER.
SELECT COUNT(*) AS NON_NUMERIC_LEAVE_DAYS
FROM XXZP.XXZP_SICK_LEAVE
WHERE LEAVE_DAYS IS NOT NULL
  AND VALIDATE_CONVERSION(TRIM(LEAVE_DAYS) AS NUMBER) = 0;

SELECT COUNT(*) AS EXISTING_FRACTIONAL_LEAVE_DAYS
FROM XXZP.XXZP_SICK_LEAVE
WHERE LEAVE_DAYS <> TRUNC(LEAVE_DAYS);

SELECT TABLE_NAME, COLUMN_NAME, IDENTITY_COLUMN
FROM ALL_TAB_IDENTITY_COLS
WHERE OWNER = 'XXZP'
  AND (TABLE_NAME = 'XXZP_SICK_LEAVE' AND COLUMN_NAME = 'HEADER_ID'
       OR TABLE_NAME = 'XXZP_ALL_ATTACHMENTS' AND COLUMN_NAME = 'HEADER_ID')
ORDER BY TABLE_NAME;

SELECT CONSTRAINT_NAME, TABLE_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM ALL_CONSTRAINTS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND CONSTRAINT_NAME IN ('XXZP_SL_FROM_DAY_TYPE_CK', 'XXZP_SL_TO_DAY_TYPE_CK')
ORDER BY CONSTRAINT_NAME;

SELECT CONSTRAINT_NAME
FROM ALL_CONS_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND COLUMN_NAME = 'LEAVE_DAYS';

SELECT INDEX_NAME
FROM ALL_IND_COLUMNS
WHERE TABLE_OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE'
  AND COLUMN_NAME = 'LEAVE_DAYS';

SELECT TRIGGER_NAME, STATUS
FROM ALL_TRIGGERS
WHERE TABLE_OWNER = 'XXZP'
  AND TABLE_NAME = 'XXZP_SICK_LEAVE';

SELECT OWNER, NAME, TYPE
FROM ALL_DEPENDENCIES
WHERE REFERENCED_OWNER = 'XXZP'
  AND REFERENCED_NAME = 'XXZP_SICK_LEAVE';
