-- Read-only check for the Arabic salary certificate EMP_NAME_LIST dependency.
-- Run as the owner of XX_DIGI_SALARY_CERT_ARABIC.
SELECT COUNT(*) AS ARABIC_SALARY_CERT_TABLE
FROM USER_TABLES
WHERE TABLE_NAME = 'XX_DIGI_SALARY_CERT_ARABIC';

SELECT COUNT(*) AS EMP_NAME_LIST_COLUMNS
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'XX_DIGI_SALARY_CERT_ARABIC'
  AND COLUMN_NAME = 'EMP_NAME_LIST';
