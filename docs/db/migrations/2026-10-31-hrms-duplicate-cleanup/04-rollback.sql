  REQUESTED_BY, REQUESTER_NAME, REQUEST_DATE, JOB_ID, JOB_NAME, DEPT_ID, DEPT_NAME, DATE_NEEDED,
  REASON_OF_REQ, REPLACEMENT_FOR, REASON, BUDGETED, BUDGETED_SAL, HIGH_SCHOOL, DIPLOMA,
