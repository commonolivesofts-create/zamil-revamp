-- EMPLOYEE-CLEARANCE-PERSON-ID-001 rollback. Stops if any clearance row needs >10 digits.

DECLARE
  v_wide_id_count PLS_INTEGER;
BEGIN
  SELECT
      (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_HEADER WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_IT WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_EMPLOYEES WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_QUALITY WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_WH WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_ACCOUNTS WHERE ABS(PERSON_ID) >= 10000000000)
    + (SELECT COUNT(*) FROM XXZP.XX_CLEARANCE_ADMIN WHERE ABS(PERSON_ID) >= 10000000000)
    INTO v_wide_id_count
    FROM DUAL;

  IF v_wide_id_count <> 0 THEN
    RAISE_APPLICATION_ERROR(-20106, 'Rollback stopped: clearance rows contain PERSON_ID values above NUMBER(10,0)');
  END IF;
END;
/

ALTER TABLE XXZP.XX_CLEARANCE_HEADER MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_IT MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_EMPLOYEES MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_QUALITY MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_WH MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_ACCOUNTS MODIFY (PERSON_ID NUMBER(10,0));
ALTER TABLE XXZP.XX_CLEARANCE_ADMIN MODIFY (PERSON_ID NUMBER(10,0));
