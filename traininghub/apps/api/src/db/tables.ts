// The whole TrainingHub data model. One definition drives the Oracle DDL (migrate), the SQL
// the Oracle store builds, and the in-memory store used for development and tests.
// Column names are camelCase here and UPPER_SNAKE in Oracle. Avoid Oracle reserved words.

export type ColType = 'int' | 'num' | 'text' | 'date' | 'ts' | 'flag';
export interface Col {
  t: ColType;
  len?: number;
  req?: true;
  /** Oracle default expression for new rows (used by DDL only). */
  def?: string;
}
type Val<C extends Col> = C['t'] extends 'int' | 'num' ? number : C['t'] extends 'flag' ? boolean : string;
export type RowOf<D extends TableDef> = {
  -readonly [K in keyof D['cols']]: D['cols'][K]['req'] extends true
    ? Val<D['cols'][K]>
    : Val<D['cols'][K]> | null;
};

export interface TableDef {
  /** Logical name; the Oracle table is PREFIX + name. */
  name: string;
  pk: string;
  /** pk is an identity column generated by the database. */
  identity: boolean;
  cols: Record<string, Col>;
  unique?: readonly (readonly string[])[];
  indexes?: readonly (readonly string[])[];
}

const int = { t: 'int' } as const;
const intR = { t: 'int', req: true } as const;
const num = { t: 'num' } as const;
const txt = (len: number) => ({ t: 'text', len }) as const;
const txtR = (len: number) => ({ t: 'text', len, req: true }) as const;
const dateR = { t: 'date', req: true } as const;
const ts = { t: 'ts' } as const;
const tsR = { t: 'ts', req: true } as const;
const flag = (def: 'Y' | 'N' = 'N') => ({ t: 'flag', req: true, def: `'${def}'` }) as const;
const id = intR;

function table<const D extends TableDef>(d: D): D {
  return d;
}

