-- LETTERS-SCHEMA-001: the storage the Salary Certificate and Business Visa Letter APIs expect.
-- APPLIED on TEST (zpadwtest) on 2026-11-04 at the owner's request (gate G1); see README.md.
-- Run as the application schema owner, after 00-precheck.sql returns the expected values.
-- DDL commits implicitly; the rollback is 02-rollback.sql. No rows are inserted or changed.
--
-- Why: both reports fail on TEST.
--   Salary certificate (English and Arabic): the repositories read, search and write TO_EMP_NAME
--     (the certificate's "To" addressee), which neither table has -> ORA-00904. Saving fails too.
--   Business visa letter: the repository uses XX_DIGI_BUSINESS_VISA_LETTERS, which does not
--     exist -> ORA-00942 for the list, the form and saving.

-- 1. Salary certificates: the "To" addressee (required by the API's write schema, max 1000).
--    Nullable: existing certificates have no stored addressee.
ALTER TABLE XX_DIGI_SALARY_CERT ADD (TO_EMP_NAME VARCHAR2(1000 CHAR));
ALTER TABLE XX_DIGI_SALARY_CERT_ARABIC ADD (TO_EMP_NAME VARCHAR2(1000 CHAR));

-- 2. Business visa letters. Columns and sizes mirror the API
--    (server/src/modules/hr/business-visa-letters/visitingVisa.repository.js FIELDS and
--    visitingVisa.validation.js writeBody). ID is generated by Oracle (the insert reads it back
--    with RETURNING ID); CREATED_AT / UPDATED_AT are set with SYSTIMESTAMP by the API.
CREATE TABLE XX_DIGI_BUSINESS_VISA_LETTERS (
  ID                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DIVISION_ID           VARCHAR2(50 CHAR),
  REF_NO                VARCHAR2(50 CHAR),
  LETTER_DATE           DATE,
  CONSUL_GENERAL        VARCHAR2(1000 CHAR),
  EMBASSY               VARCHAR2(1000 CHAR),
  EMBASSY_LOCATION      VARCHAR2(1000 CHAR),
  OPENING_TEXT          VARCHAR2(1000 CHAR),
  REQUEST_FOR           VARCHAR2(50 CHAR),
  SUBJECT               VARCHAR2(1000 CHAR),
  EMPLOYEE_NAME         VARCHAR2(250 CHAR),
  NATIONALITY           VARCHAR2(1000 CHAR),
  PASSPORT_NO           VARCHAR2(1000 CHAR),
  PASSPORT_DATE         DATE,
  ID_NO                 VARCHAR2(1000 CHAR),
  ID_EXPIRATION_DATE    DATE,
  JOB_TITLE             VARCHAR2(1000 CHAR),
  EMPLOYED_SINCE        DATE,
  CONTRACT_EXPIRY       DATE,
  CONTRACT_NATURE       VARCHAR2(1000 CHAR),
  MONTHLY_SALARY        NUMBER,
  VISIT_PLACE           VARCHAR2(1000 CHAR),
  VISIT_DAYS            NUMBER,
  VISIT_PURPOSE         VARCHAR2(1000 CHAR),
  EXPENSE_EMPLOYEE_NAME VARCHAR2(1000 CHAR),
  EXPENSE_BORNE_BY      VARCHAR2(1000 CHAR),
  RETURN_EMPLOYEE_NAME  VARCHAR2(1000 CHAR),
  RETURN_STATEMENT      VARCHAR2(1000 CHAR),
  CLOSING_TEXT          VARCHAR2(1000 CHAR),
  STATUS                VARCHAR2(10 CHAR) DEFAULT 'DRAFT',
  EMBASSY_AR            VARCHAR2(1000 CHAR),
  JOB_TITLE_AR          VARCHAR2(1000 CHAR),
  CONTRACT_NATURE_AR    VARCHAR2(1000 CHAR),
  NATIONALITY_AR        VARCHAR2(1000 CHAR),
  VISIT_PURPOSE_AR      VARCHAR2(1000 CHAR),
  CREATED_BY            VARCHAR2(100 CHAR),
  CREATED_AT            TIMESTAMP(6),
  UPDATED_BY            VARCHAR2(100 CHAR),
  UPDATED_AT            TIMESTAMP(6),
  CONSTRAINT XX_DIGI_BVL_PK PRIMARY KEY (ID),
  CONSTRAINT XX_DIGI_BVL_STATUS_CK CHECK (STATUS IN ('DRAFT', 'FINAL')),
  CONSTRAINT XX_DIGI_BVL_REQUEST_FOR_CK CHECK (REQUEST_FOR IS NULL OR REQUEST_FOR IN ('Business Single', 'Business Multiple'))
);

-- The report sorts and filters by letter date and division; the API checks reference numbers
-- for duplicates case-insensitively.
CREATE INDEX XX_DIGI_BVL_LETTER_DATE_IX ON XX_DIGI_BUSINESS_VISA_LETTERS (LETTER_DATE);
CREATE INDEX XX_DIGI_BVL_DIVISION_IX ON XX_DIGI_BUSINESS_VISA_LETTERS (DIVISION_ID);
CREATE INDEX XX_DIGI_BVL_REF_NO_IX ON XX_DIGI_BUSINESS_VISA_LETTERS (UPPER(TRIM(REF_NO)));
