SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME IN (
    'XX_CLEARANCE_HEADER', 'XX_CLEARANCE_IT', 'XX_CLEARANCE_EMPLOYEES',
    'XX_CLEARANCE_QUALITY', 'XX_CLEARANCE_WH', 'XX_CLEARANCE_ACCOUNTS',
    'XX_CLEARANCE_ADMIN'
  )
  AND COLUMN_NAME = 'PERSON_ID'
ORDER BY TABLE_NAME;

SELECT COUNT(*) AS CLEARANCE_COLUMNS_NOT_AT_SOURCE_PRECISION
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'XXZP'
  AND TABLE_NAME IN (
    'XX_CLEARANCE_HEADER', 'XX_CLEARANCE_IT', 'XX_CLEARANCE_EMPLOYEES',
    'XX_CLEARANCE_QUALITY', 'XX_CLEARANCE_WH', 'XX_CLEARANCE_ACCOUNTS',
    'XX_CLEARANCE_ADMIN'
  )
  AND COLUMN_NAME = 'PERSON_ID'
  AND (DATA_TYPE <> 'NUMBER'
       OR NVL(DATA_PRECISION, -1) <> 18
       OR NVL(DATA_SCALE, -1) <> 0);
