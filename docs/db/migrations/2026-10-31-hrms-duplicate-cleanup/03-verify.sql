-- No duplicate IDs remain: expect 0, 0, 0.
SELECT (SELECT COUNT(*) FROM (SELECT 1 FROM XXZP.XXZPI_PER_REQUISITIONS_ALL
                               GROUP BY REQUISITION_ID HAVING COUNT(*) > 1)) AS REQ_DUPS,
       (SELECT COUNT(*) FROM (SELECT 1 FROM XXZP.XXZP_INTERVW_ASSESMNT_HEADER_T
                               GROUP BY HEADER_ID HAVING COUNT(*) > 1)) AS INT_DUPS,
       (SELECT COUNT(*) FROM (SELECT 1 FROM XXZP.XXZP_ALL_ATTACHMENTS
                               GROUP BY HEADER_ID HAVING COUNT(*) > 1)) AS ATT_DUPS
  FROM DUAL;

-- Every backed-up key still exists exactly once: expect REQ 1, INT_677 1, INT_NEW 1, ATT_MISSING 0.
SELECT (SELECT COUNT(*) FROM XXZP.XXZPI_PER_REQUISITIONS_ALL WHERE REQUISITION_ID = 100800) AS REQ,
       (SELECT COUNT(*) FROM XXZP.XXZP_INTERVW_ASSESMNT_HEADER_T WHERE HEADER_ID = 677) AS INT_677,
       (SELECT COUNT(*) FROM XXZP.XXZP_INTERVW_ASSESMNT_HEADER_T
         WHERE HEADER_ID = (SELECT NEW_HEADER_ID FROM XXZP.XXZP_DUPFIX_INT_MAP)) AS INT_NEW,
       (SELECT COUNT(*) FROM (SELECT DISTINCT HEADER_ID FROM XXZP.XXZP_DUPFIX_ATT_BAK
                              MINUS SELECT HEADER_ID FROM XXZP.XXZP_ALL_ATTACHMENTS)) AS ATT_MISSING
  FROM DUAL;

-- Interview children: expect 677 -> 2 per table (Approved creator), new ID -> 1 per table.
SELECT 'EVAL' T, HEADER_ID, COUNT(*) FROM XXZP.XXZP_INTERVIEW_EVAL_T
